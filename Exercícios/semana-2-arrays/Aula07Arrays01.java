public class Aula07Arrays01 {
    static void main(String[] args) {

        // Array serve pra declarar mais de um valor na mesma variável.
        // Array é sempre um objeto.

        int [] idades = new int[3];
        idades[0] = 21;
        idades[1] = 15;
        idades[2] = 11;

        System.out.println(idades [0]);
    }
}
