public class Aula06EstruturasDeRepeticao03 {
    static void main(String[] args) {
        
        //Break: serve para parar um loop, ou seja, ele interrompe a execução do loop
        for (int i = 0; i <= 50; i++) {
            if (i > 25){
                break;
            }
            System.out.println(i);

        }
    }
}
